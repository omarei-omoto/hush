#!/usr/bin/env node
/**
 * hush as a single file, for people who do not have Node 22 (F-8).
 *
 * Bun's `--compile`, not Node's SEA: measured on the same machine, Bun's binary
 * is ~60 MB and starts in ~40 ms, cross-compiles every target from one runner,
 * and runs hush's node:crypto unchanged (X25519, Ed25519, P-256, HKDF, AES-GCM —
 * the whole suite runs against it: HUSH_TEST_BINARY, below). SEA needs a build
 * per platform and came out over 100 MB.
 *
 *   node scripts/build-binaries.mjs              this machine's platform only
 *   node scripts/build-binaries.mjs --all        every release target
 *   node scripts/build-binaries.mjs --target linux-x64 --target darwin-arm64
 *
 * Output goes to release/: `hush-<target>` (`.exe` on Windows) and SHA256SUMS.
 *
 * Two of Bun's defaults are wrong for hush and are turned off here:
 *
 *   - a compiled program loads `.env` from the working directory into its
 *     environment. For a secrets manager that is backwards twice over: the
 *     plaintext file it exists to replace would be read on every run, and a
 *     cloned repository could set HUSH_VAULT, HUSH_IDENTITY or HUSH_NO_DIALOG
 *     for anyone who runs hush inside it;
 *   - it loads `bunfig.toml` from the working directory, whose `preload` runs a
 *     script of the repository's choosing inside hush, before hush.
 *
 * test/binary.test.ts checks both stay off in the binary it is given.
 *
 * The files hush reads from its own package at runtime (src/assets.ts) are
 * embedded: the generated entry point puts their text on
 * `globalThis.__HUSH_ASSETS__` before any of hush loads. So is the finished
 * `hush ui` page, for the reason in assets.ts builtPage.
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { arch, platform } from "node:os";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { ASSET_FILES } = await import(pathToFileURL(join(root, "src", "assets.ts")).href);
const { VERSION } = await import(pathToFileURL(join(root, "src", "version.ts")).href);
const { PAGE } = await import(pathToFileURL(join(root, "src", "ui-page.ts")).href);

/** Release name → Bun target. Every x64 target uses the baseline build: it runs on CPUs without AVX2, and under Rosetta, which has none. */
export const TARGETS = {
  "darwin-arm64": "bun-darwin-arm64",
  "darwin-x64": "bun-darwin-x64-baseline",
  "linux-x64": "bun-linux-x64-baseline",
  "linux-arm64": "bun-linux-arm64",
  // Alpine and other musl systems: the glibc builds do not start there.
  "linux-x64-musl": "bun-linux-x64-musl-baseline",
  "linux-arm64-musl": "bun-linux-arm64-musl",
  "windows-x64": "bun-windows-x64-baseline",
};

const host = `${platform() === "win32" ? "windows" : platform()}-${arch()}`;

function parse(argv) {
  if (argv.includes("--help")) {
    process.stdout.write(`usage: node scripts/build-binaries.mjs [--all | --target <${Object.keys(TARGETS).join("|")}> …] [--out dir]\n`);
    process.exit(0);
  }
  const out = argv.includes("--out") ? argv[argv.indexOf("--out") + 1] : join(root, "release");
  if (argv.includes("--all")) return { targets: Object.keys(TARGETS), out };
  const targets = argv.flatMap((a, i) => (a === "--target" ? [argv[i + 1]] : []));
  for (const t of targets) if (!TARGETS[t]) fail(`unknown target "${t}" — one of ${Object.keys(TARGETS).join(", ")}`);
  if (!targets.length && !TARGETS[host]) fail(`no binary target for this machine (${host}); pass --target`);
  return { targets: targets.length ? targets : [host], out };
}

function fail(message) {
  process.stderr.write(`build-binaries: ${message}\n`);
  process.exit(1);
}

function bun() {
  const r = spawnSync("bun", ["--version"], { encoding: "utf8" });
  if (r.status !== 0) fail("bun is not installed — https://bun.sh (it is only needed to build the binaries)");
  return r.stdout.trim();
}

/** The entry point: the embedded assets, then hush. Written under .build/, which git ignores. */
function writeEntry() {
  const assets = {};
  for (const [name, rel] of Object.entries(ASSET_FILES)) {
    const path = join(root, "src", rel);
    if (!existsSync(path)) fail(`asset "${name}" is missing: ${path}`);
    assets[name] = readFileSync(path, "utf8");
  }
  // The ui page, finished: its parts are String.raw templates, whose value Bun's
  // ASCII-only output would change (src/assets.ts, builtPage).
  assets.page = PAGE;
  const dir = join(root, ".build");
  mkdirSync(dir, { recursive: true });
  const entry = join(dir, "entry.ts");
  writeFileSync(
    entry,
    [
      "// Generated by scripts/build-binaries.mjs — do not edit.",
      `(globalThis as { __HUSH_ASSETS__?: Record<string, string> }).__HUSH_ASSETS__ = ${JSON.stringify(assets)};`,
      'await import("../src/cli.ts");',
      "",
    ].join("\n"),
  );
  return entry;
}

function build(entry, target, out) {
  const file = join(out, `hush-${target}${target.startsWith("windows") ? ".exe" : ""}`);
  const args = [
    "build",
    "--compile",
    `--target=${TARGETS[target]}`,
    "--no-compile-autoload-dotenv",
    "--no-compile-autoload-bunfig",
    "--no-compile-autoload-tsconfig",
    "--no-compile-autoload-package-json",
    // Version resources (--windows-title and friends) can only be written by a
    // Windows host; the release builds every target from one Linux runner.
    entry,
    "--outfile",
    file,
  ];
  const r = spawnSync("bun", args, { cwd: root, encoding: "utf8" });
  if (r.status !== 0) fail(`bun build for ${target} failed:\n${r.stdout}${r.stderr}`);
  return file;
}

const sha256 = (file) => createHash("sha256").update(readFileSync(file)).digest("hex");

// Only when run, not when imported (test/distribution.test.ts reads TARGETS).
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();

function main() {
  const { targets, out } = parse(process.argv.slice(2));
  process.stdout.write(`hush ${VERSION} with bun ${bun()} → ${out}\n`);
  mkdirSync(out, { recursive: true });
  const entry = writeEntry();
  const sums = [];
  try {
    for (const target of targets) {
      const file = build(entry, target, out);
      const name = file.slice(out.length + 1);
      sums.push(`${sha256(file)}  ${name}`);
      process.stdout.write(`  ✓ ${name}\n`);
    }
  } finally {
    rmSync(join(root, ".build"), { recursive: true, force: true });
  }
  // Sorted by name, so SHA256SUMS does not depend on the order targets were asked for.
  writeFileSync(join(out, "SHA256SUMS"), sums.sort((a, b) => a.split("  ")[1].localeCompare(b.split("  ")[1])).join("\n") + "\n");
  process.stdout.write(`  ✓ SHA256SUMS\n`);
}
