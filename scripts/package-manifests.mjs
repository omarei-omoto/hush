#!/usr/bin/env node
/**
 * Package-manager manifests for a release's binaries, from its SHA256SUMS:
 *
 *   Formula/hush.rb                      Homebrew (the omarei-omoto/homebrew-tap repository)
 *   scoop/hush.json                      Scoop (a bucket, or scoop install <url>)
 *   winget/omarei.hush.*.yaml            winget-pkgs (a pull request per release)
 *
 *   node scripts/package-manifests.mjs --version 1.0.0 --sums release/SHA256SUMS [--out release/manifests]
 *
 * The release workflow runs this after the binaries are built and attaches the
 * output to the GitHub release; RELEASING.md says where each file goes. Every
 * URL points at the GitHub release for the tag, and every hash comes from the
 * SHA256SUMS that the workflow computed and attested — nothing is typed by hand.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "omarei-omoto/hush";
const HOMEPAGE = `https://github.com/${REPO}`;
const DESCRIPTION = "Envelope-encrypted team secrets your AI agent can use but never read";
const LICENSE = "MIT";

export function parseSums(text) {
  const sums = {};
  for (const line of text.split("\n")) {
    const m = /^([0-9a-f]{64})\s+\*?(\S+)$/.exec(line.trim());
    if (m) sums[m[2]] = m[1];
  }
  return sums;
}

function need(sums, file) {
  if (!sums[file]) throw new Error(`SHA256SUMS does not list ${file}`);
  return sums[file];
}

const url = (version, file) => `${HOMEPAGE}/releases/download/v${version}/${file}`;

export function homebrewFormula(version, sums) {
  const block = (file) =>
    [`      url "${url(version, file)}"`, `      sha256 "${need(sums, file)}"`].join("\n");
  return `# Generated by scripts/package-manifests.mjs for hush ${version} — do not edit.
class Hush < Formula
  desc "${DESCRIPTION}"
  homepage "${HOMEPAGE}"
  version "${version}"
  license "${LICENSE}"

  on_macos do
    on_arm do
${block("hush-darwin-arm64")}
    end
    on_intel do
${block("hush-darwin-x64")}
    end
  end

  on_linux do
    on_arm do
${block("hush-linux-arm64")}
    end
    on_intel do
${block("hush-linux-x64")}
    end
  end

  def install
    bin.install Dir["hush-*"].first => "hush"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/hush --version").strip
  end
end
`;
}

export function scoopManifest(version, sums) {
  const file = "hush-windows-x64.exe";
  return (
    JSON.stringify(
      {
        version,
        description: DESCRIPTION,
        homepage: HOMEPAGE,
        license: LICENSE,
        architecture: { "64bit": { url: url(version, file), hash: need(sums, file) } },
        bin: [[file, "hush"]],
        checkver: { github: HOMEPAGE },
        autoupdate: {
          architecture: {
            "64bit": {
              url: `${HOMEPAGE}/releases/download/v$version/${file}`,
              hash: { url: `${HOMEPAGE}/releases/download/v$version/SHA256SUMS` },
            },
          },
        },
      },
      null,
      2,
    ) + "\n"
  );
}

export function wingetManifests(version, sums) {
  const file = "hush-windows-x64.exe";
  const id = "omarei.hush";
  const head = (type) =>
    `# Generated by scripts/package-manifests.mjs for hush ${version} — do not edit.\n` +
    `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.1.9.0.schema.json\n`;
  return {
    [`${id}.yaml`]:
      head("version") +
      [`PackageIdentifier: ${id}`, `PackageVersion: ${version}`, "DefaultLocale: en-US", "ManifestType: version", "ManifestVersion: 1.9.0", ""].join("\n"),
    [`${id}.installer.yaml`]:
      head("installer") +
      [
        `PackageIdentifier: ${id}`,
        `PackageVersion: ${version}`,
        "InstallerType: portable",
        "Commands:",
        "  - hush",
        "Installers:",
        "  - Architecture: x64",
        `    InstallerUrl: ${url(version, file)}`,
        `    InstallerSha256: ${need(sums, file).toUpperCase()}`,
        "ManifestType: installer",
        "ManifestVersion: 1.9.0",
        "",
      ].join("\n"),
    [`${id}.locale.en-US.yaml`]:
      head("defaultLocale") +
      [
        `PackageIdentifier: ${id}`,
        `PackageVersion: ${version}`,
        "PackageLocale: en-US",
        "Publisher: omarei",
        "PackageName: hush",
        `PackageUrl: ${HOMEPAGE}`,
        `License: ${LICENSE}`,
        `ShortDescription: ${DESCRIPTION}`,
        "Tags:",
        "  - secrets",
        "  - security",
        "  - ai",
        "  - mcp",
        "ManifestType: defaultLocale",
        "ManifestVersion: 1.9.0",
        "",
      ].join("\n"),
  };
}

export function writeManifests(version, sumsText, out) {
  const sums = parseSums(sumsText);
  mkdirSync(join(out, "Formula"), { recursive: true });
  mkdirSync(join(out, "scoop"), { recursive: true });
  mkdirSync(join(out, "winget"), { recursive: true });
  writeFileSync(join(out, "Formula", "hush.rb"), homebrewFormula(version, sums));
  writeFileSync(join(out, "scoop", "hush.json"), scoopManifest(version, sums));
  for (const [name, text] of Object.entries(wingetManifests(version, sums))) writeFileSync(join(out, "winget", name), text);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const arg = (name) => {
    const i = process.argv.indexOf(`--${name}`);
    return i === -1 ? undefined : process.argv[i + 1];
  };
  const version = arg("version")?.replace(/^v/, "");
  const sums = arg("sums");
  if (!version || !sums) {
    process.stderr.write("usage: node scripts/package-manifests.mjs --version x.y.z --sums release/SHA256SUMS [--out dir]\n");
    process.exit(1);
  }
  const out = arg("out") ?? join(dirname(sums), "manifests");
  writeManifests(version, readFileSync(sums, "utf8"), out);
  process.stdout.write(`manifests for hush ${version} → ${out}\n`);
}
